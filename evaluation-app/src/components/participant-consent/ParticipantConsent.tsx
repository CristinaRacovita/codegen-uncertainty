import { Box, Checkbox, FormControlLabel, FormGroup } from '@mui/material';
import { useState } from 'react';

export interface ParticipantConsentData {
    consent: boolean;
}

interface ParticipantConsentProps {
    onProfileUpdate: (profile: ParticipantConsentData) => void;
}

export default function ParticipantConsent({ onProfileUpdate }: ParticipantConsentProps) {
    // Initialize profile from parent component's state
    const [profile, setProfile] = useState<ParticipantConsentData>(() => {
        const savedProfile = localStorage.getItem('evaluationProfileData');
        return savedProfile ? JSON.parse(savedProfile) : {
            consent: false
        };
    });

    const handleCheckboxChange = (field: keyof ParticipantConsentData) => (
        event: React.ChangeEvent<HTMLInputElement>
    ) => {
        const newProfile = {
            ...profile,
            [field]: event.target.checked
        };
        setProfile(newProfile);
        onProfileUpdate(newProfile);
    };


    return (
        <Box sx={{ display: 'flex', flexDirection: 'column', alignItems: 'start' }}>
            <div style={{ textAlign: 'left', }}>
                Before starting the task, please read the information below and confirm your agreement to participate.
            </div>
            <div style={{ textAlign: 'left', marginTop: '10px' }}>
                This study is part of a Master's thesis research project on the usefulness of explanations in AI-generated code. By taking part, you will help us understand whether confidence indicators (e.g., color-coded lines) affect how developers interact with and improve AI-generated code.
            </div>
            <div style={{ textAlign: 'left', fontWeight: 'bold', marginTop: '15px', color: '#203568' }}>
                Your participantion:
            </div>
            <ul style={{ textAlign: 'left' }}>
                <li>Is voluntary and you can stop at any time before submitting your task.</li>
                <li>Is anonymous — no personal or identifying data will be collected.</li>
                <li>Will take approximately 10-15 minutes.</li>
                <li>Involves reviewing code generated by an AI and submitting your version of it.</li>
            </ul>

            <div style={{ textAlign: 'left' }}>
                The collected data will be used for academic purposes, including in a Master's thesis and potentially in future research publications. Results will only be reported in aggregate form.
            </div>
            <div style={{ textAlign: 'left', marginTop: '10px' }}>
                If you have questions or concerns, you may contact the researcher at any time.
            </div>
            <div style={{ textAlign: 'left', fontWeight: 'bold', marginTop: '15px', color: '#203568' }}>
                Please confirm by checking the box below that:
            </div>
            <ul style={{ textAlign: 'left' }}>
                <li>You are at least 18 years old.</li>
                <li>Your are fluent in English.</li>
                <li>You are familiar with writing code in Python.</li>
                <li>You understand the purpose of the study and what is expected of you.</li>
                <li>You voluntarily agree to participate in this research.</li>
            </ul>

            <FormGroup>
                <FormControlLabel required control={<Checkbox onChange={handleCheckboxChange('consent')} />} label="I agree to participate in this study" style={{ fontStyle: 'italic', color: '#01adee' }} />
            </FormGroup>

        </Box>
    );
}
